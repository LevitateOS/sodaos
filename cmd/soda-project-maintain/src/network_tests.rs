use super::parse_prefix;

#[test]
fn prefix_grammar_family_and_bounds() {
    for value in [
        "10.0.0.0/0",
        "10.0.0.0/32",
        "::/0",
        "::/128",
        "fe80::1/128",
        "::ffff:1.2.3.4/128",
        "1:2:3:4:5:6:1.2.3.4/128",
        "2001:db8::192.0.2.1/64",
        "::192.0.2.1/128",
    ] {
        assert_eq!(parse_prefix(value), Ok(()), "{value}");
    }

    for value in [
        "1.2.3.4/33",
        "::/129",
        "10.0.0.0/-1",
        "10.0.0.0/",
        "10.0.0.0/08",
        "10.0.0.0/+8",
        "10.0.0.0",
        "010.0.0.0/8",
        "1.2.3.4/99999999999999999999999",
        "fe80::1%eth0/64",
        "1.2.3.4%eth0/24",
        "1:2:3/64",
        "1::2::3/64",
        "::gggg/1",
    ] {
        assert!(parse_prefix(value).is_err(), "accepted {value:?}");
    }
}
