import {expect, test} from 'bun:test';
import {generated, language, measure} from './check';
import {measureTypeScript} from './typescript';

test('excludes tests, generated headers and dependencies, retains product build package', () => {
  for (const path of [
    'internal/x_test.go',
    'frontend/x.test.ts',
    'cmd/app/tests.rs',
    'cmd/app/src/tests/mod.rs',
    'vendor/lib.go',
    'node_modules/x.ts',
    'lib/a/target/x.rs',
    'tools/lit-check/fixtures/a.ts',
  ])
    expect(language(path)).toBeUndefined();
  expect(language('internal/release/build/run.go')).toBe('go');
  expect(generated('// Code generated by mockgen. DO NOT EDIT.\npackage fake')).toBe(true);
  expect(generated('// handwritten production\npackage real')).toBe(false);
});

test('TypeScript counts modern branches and separates nested functions', () => {
  const rows = measureTypeScript([
    {
      Path: 'frontend/example.ts',
      Text: 'export function f(x = 0) { if (x && x > 1) return x?.value ?? 2; return () => x ? 1 : 0; }',
    },
  ]);
  expect(rows.map((r) => r.score)).toEqual([6, 2]);
  expect(() => measureTypeScript([{Path: 'frontend/bad.ts', Text: 'function {'}])).toThrow();
});

test('Go parser counts decisions and rejects malformed source', () => {
  const rows = measure([
    {
      Path: 'internal/example.go',
      Text: 'package p\nfunc Run(a, b bool) { if a && b {}\nfor a {}\nswitch { case b: default: } }',
    },
  ]);
  expect(rows[0]!.score).toBe(5);
  expect(() => measure([{Path: 'internal/bad.go', Text: 'package p; func {'}])).toThrow();
});

test('Rust skips inline cfg(test), test methods and cfg(all(test,...)) modules', () => {
  const rows = measure([
    {
      Path: 'cmd/example/src/lib.rs',
      Text: `
    fn production(a: bool, b: bool) -> Option<()> { if a && b { return None; } Some(())?; Some(()) }
    #[cfg(test)] mod tests { fn large() { if true {} if true {} } }
    #[cfg(all(test, feature = "fixture"))] mod more { fn ignored() { if true {} } }
    struct A; impl A { fn method(&self) { match 1 { 0 | 1 => (), _ => () } } #[test] fn test_only() {} }
    #[cfg(not(test))] fn retained() {}
    trait T { fn default_method(&self) { while false {} } }
  `,
    },
  ]);
  expect(rows.map((r) => [r.name, r.score])).toEqual([
    ['production', 4],
    ['A::method', 3],
    ['retained', 1],
    ['T::default_method', 2],
  ]);
  expect(() => measure([{Path: 'cmd/example/src/bad.rs', Text: 'fn {'}])).toThrow();
});

test('Rust excludes test-only crates, expressions, arms and nested functions in test blocks', () => {
  const rows = measure([
    {Path: 'cmd/example/src/only.rs', Text: '#![cfg(test)] fn skipped() { if true {} }'},
    {
      Path: 'cmd/example/src/mixed.rs',
      Text: `fn kept() {
      #[cfg(test)] { if true {} fn skipped() { if true {} } }
      match 0 { #[cfg(test)] 1 if true => { if true {} }, _ => () }
    }`,
    },
  ]);
  expect(rows.map((r) => [r.name, r.score])).toEqual([['kept', 1]]);
});
